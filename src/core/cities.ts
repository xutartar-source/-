export interface City {
  name: string
  longitude: number
}

export interface Province {
  name: string
  cities: City[]
}

export const PROVINCES: Province[] = RAW.trim()
  .split('\n')
  .map((line) => {
    const [name, rest] = line.split(':')
    const cities = rest.split(' ').map((item) => {
      const m = /^(\D+)([\d.]+)$/.exec(item)!
      return { name: m[1], longitude: Number(m[2]) }
    })
    return { name, cities }
  })

export function findCity(province: string, city: string): City | undefined {
  return PROVINCES.find((p) => p.name === province)?.cities.find((c) => c.name === city)
}
